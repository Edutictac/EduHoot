function t(key){
    var chain = lang === 'va' ? ['va', 'ca', 'es'] : [lang, 'en', 'es'];
    for(var i = 0; i < chain.length; i++){
        var dict = i18n[chain[i]];
        if(dict && dict[key]) return dict[key];
    }
    return key;
}

// Traduce lo que queda fuera de las apps de Vue (cabecera, aviso de Stage y
// pie); dentro, las plantillas usan t() directamente.
function applyStaticTranslations(){
    document.querySelectorAll('[data-i18n]').forEach(function(el){
        var key = el.getAttribute('data-i18n');
        // Avoid touching labels with form controls to prevent hiding inputs
        if(el.tagName === 'LABEL' && el.querySelector('input,select,textarea')){
            var textNode = Array.from(el.childNodes).find(function(node){
                if(node.nodeType === Node.TEXT_NODE && node.textContent.trim()){
                    return true;
                }
                if(node.nodeType === Node.ELEMENT_NODE && !['INPUT','SELECT','TEXTAREA'].includes(node.tagName)){
                    return true;
                }
                return false;
            });
            if(textNode){
                if(textNode.nodeType === Node.TEXT_NODE){
                    textNode.textContent = t(key) + ' ';
                }else{
                    textNode.textContent = t(key);
                }
            }else{
                var span = document.createElement('span');
                span.textContent = t(key);
                el.insertBefore(span, el.firstChild);
            }
            return;
        }
        if(key === 'subtitle'){
            el.innerHTML = t(key);
        }else{
            el.textContent = t(key);
        }
    });
    var langSelect = document.getElementById('lang-select');
    if(langSelect) langSelect.value = lang;
}
